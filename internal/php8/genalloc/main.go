// Command genalloc writes alloc_gen.go: one slab per AST node type that the
// grammar and builder allocate through nodeAlloc.
package main

import (
	"bytes"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

var allocCall = regexp.MustCompile(`\.alloc\.([A-Z][A-Za-z]*)\(ast\.`)

func main() {
	types := map[string]bool{}
	for _, f := range []string{"php8.y", "builder.go"} {
		src, err := os.ReadFile(f)
		if err != nil {
			panic(err)
		}
		for _, m := range allocCall.FindAllSubmatch(src, -1) {
			types[string(m[1])] = true
		}
	}

	names := make([]string, 0, len(types))
	for t := range types {
		names = append(names, t)
	}
	sort.Strings(names)

	field := func(t string) string { return strings.ToLower(t[:1]) + t[1:] }

	var b bytes.Buffer
	b.WriteString(`// Code generated by genalloc. DO NOT EDIT.

package php8

import "github.com/pyxsoft/php-parser/pkg/ast"

// nodeAlloc hands out AST nodes from per-type slabs. A nil *nodeAlloc
// allocates every node on the heap, which keeps parser.Parse memory-neutral
// for one-shot use; reusable Arenas pass a non-nil one.
type nodeAlloc struct {
`)
	for _, t := range names {
		fmt.Fprintf(&b, "\t%s slab[ast.%s]\n", field(t), t)
	}
	b.WriteString("}\n\nfunc (a *nodeAlloc) reset() {\n")
	for _, t := range names {
		fmt.Fprintf(&b, "\ta.%s.reset()\n", field(t))
	}
	b.WriteString("}\n\n// capBytes is the memory held by all slabs.\nfunc (a *nodeAlloc) capBytes() int {\n\tn := 0\n")
	for _, t := range names {
		fmt.Fprintf(&b, "\tn += a.%s.capBytes()\n", field(t))
	}
	b.WriteString("\treturn n\n}\n")
	for _, t := range names {
		fmt.Fprintf(&b, `
func (a *nodeAlloc) %[1]s(v ast.%[1]s) *ast.%[1]s {
	if a == nil {
		// new + copy instead of &v: taking v's address would move v to the
		// heap on every call, including the slab path.
		p := new(ast.%[1]s)
		*p = v
		return p
	}
	return newNode(&a.%[2]s, v)
}
`, t, field(t))
	}

	if err := os.WriteFile("alloc_gen.go", b.Bytes(), 0o644); err != nil {
		panic(err)
	}
}
